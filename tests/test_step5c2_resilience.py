"""Tests for Step 5C-2: smart path extraction, redacted evidence, deterministic fingerprinting, and analyst invariant."""

import pytest

from savageops.agents import analyst, triage
from savageops.models import TriageReport
from savageops.sentinel import ingest


def test_extract_path_matrix():
    """extract_path accurately extracts repo-relative paths across containers, Windows, and ignores site-packages."""
    # 1. Standard relative path
    tb1 = 'File "app/pricing.py", line 12, in calculate_price'
    assert triage.extract_path(tb1) == "app/pricing.py"

    # 2. Container /app/app/pricing.py
    tb2 = 'File "/app/app/pricing.py", line 12, in calculate_price'
    assert triage.extract_path(tb2) == "app/pricing.py"

    # 3. Windows absolute path
    tb3 = 'File "D:\\kickcart\\app\\pricing.py", line 12, in calculate_price'
    assert triage.extract_path(tb3) == "app/pricing.py"

    # 4. Container root file
    tb4 = 'File "/app/billing.py", line 5, in charge'
    assert triage.extract_path(tb4) == "billing.py"

    # 5. FastAPI traceback with site-packages innermost, app/pricing.py above
    tb5 = (
        'Traceback (most recent call last):\n'
        '  File "/app/app/pricing.py", line 24, in get_discount\n'
        '    raise ZeroDivisionError("division by zero")\n'
        '  File "/app/.venv/lib/python3.12/site-packages/starlette/routing.py", line 68, in app\n'
        '    response = await func(request)\n'
    )
    assert triage.extract_path(tb5) == "app/pricing.py"

    # 6. Only external / site-packages frames -> None
    tb6 = (
        '  File "/usr/local/lib/python3.12/site-packages/uvicorn/server.py", line 82, in serve\n'
        '  File "/app/.venv/lib/python3.12/site-packages/starlette/routing.py", line 68, in app\n'
    )
    assert triage.extract_path(tb6) is None


def test_triage_redacted_evidence_validation(monkeypatch):
    """When LLM cites evidence containing [REDACTED], confidence is not dropped to 0.0."""
    raw_logs = 'Traceback (most recent call last):\n  File "app/pricing.py", line 10, in calculate\n    api_key = "secret_key_1234567890"\nValueError: invalid key\n'
    mock_report = TriageReport(
        file_path="app/pricing.py",
        line_start=10,
        line_end=10,
        error_summary="Invalid API key",
        severity="P2",
        severity_reason="Authentication failed",
        # Evidence generated by LLM from redacted prompt
        evidence=["[REDACTED]"],
        confidence=0.9,
        applicable=True,
    )

    monkeypatch.setattr(triage, "get_logs", lambda *args, **kwargs: raw_logs)
    monkeypatch.setattr(triage, "get_file", lambda *args, **kwargs: "\n" * 20)
    monkeypatch.setattr(triage, "update_incident", lambda *args, **kwargs: None)
    monkeypatch.setattr(triage, "log_run", lambda *args, **kwargs: None)
    monkeypatch.setattr(triage, "invoke_guarded", lambda *args, **kwargs: mock_report)

    alert = {"labels": {"service": "dummy-app", "alertname": "AuthFail"}}
    report = triage.run_triage("inc-redact-ev", alert)

    # Confidence must not be demoted to 0.0
    assert report.confidence == 0.9


def test_ingest_missing_fingerprint_deterministic_and_no_collision():
    """Two different alerts without fingerprint don't collide; same alert deduplicates."""
    alert1 = {
        "labels": {"alertname": "HighLatency", "service": "cart"},
        "annotations": {"description": "Cart is slow"},
    }
    alert2 = {
        "labels": {"alertname": "DatabaseError", "service": "auth"},
        "annotations": {"description": "Auth DB unreachable"},
    }

    # Clean in-memory DB before test
    from savageops.db import _memory_incidents

    _memory_incidents.clear()

    # 1. Ingest alert 1
    id1 = ingest.ingest(alert1, source="webhook")
    assert id1 is not None

    # 2. Ingest alert 2 (different labels) -> must NOT collide or be dropped as duplicate
    id2 = ingest.ingest(alert2, source="webhook")
    assert id2 is not None
    assert id1 != id2

    # 3. Ingest exact same alert 1 again -> must deduplicate (return None)
    id1_dup = ingest.ingest(alert1, source="webhook")
    assert id1_dup is None


def test_analyst_invariant_raises_on_empty_payload(monkeypatch):
    """run_analyst raises ValueError when LLM returns neither analysis nor info_request."""
    from types import SimpleNamespace

    empty_result = SimpleNamespace(info_request=None, analysis=None)

    monkeypatch.setattr(analyst, "get_file", lambda *args, **kwargs: "code")
    monkeypatch.setattr(analyst, "recent_commits", lambda *args, **kwargs: [])
    monkeypatch.setattr(analyst, "log_run", lambda *args, **kwargs: None)
    monkeypatch.setattr(analyst, "invoke_guarded", lambda *args, **kwargs: empty_result)

    triage_info = {"file_path": "app/pricing.py"}
    with pytest.raises(ValueError, match="neither analysis nor info_request"):
        analyst.run_analyst("inc-empty-analyst", triage_info)
